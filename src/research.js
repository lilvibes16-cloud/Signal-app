export function createResearchBrief(topic){if(!topic||!topic.title)throw new Error("A topic is required");return [
"# SIGNAL · Creator Research Brief",
"",
"Topic: "+topic.title,
"Category: "+topic.category,
"Format: "+topic.format,
"",
"## Concept",
topic.description,
"",
"## Suggested angle",
topic.angle,
"",
"## Search terms to validate",
...topic.keywords.map(k=>"- "+k),
"",
"## Research checklist",
"- [ ] Search YouTube for the exact topic and related keywords",
"- [ ] Record 5 recent comparable videos, dates, views, and channel sizes",
"- [ ] Check whether demand appears sustained across multiple creators",
"- [ ] Identify a distinct audience problem or curiosity hook",
"- [ ] Verify facts and sources before scripting",
"- [ ] Draft 3 titles and thumbnail concepts",
"- [ ] Choose a realistic production scope and publishing date",
"",
"## Comparable video evidence",
"| Video URL | Publish date | Views observed | Channel subscribers | Why relevant |",
"| --- | --- | --- | --- | --- |",
"| | | | | |",
"| | | | | |",
"",
"## Decision",
"Go / Revise / Pass:",
"Evidence supporting decision:",
"Risks and unknowns:",
"",
"**Data disclosure:** SIGNAL's topic scores, competition labels, and charts are illustrative demo fixtures. They are not observed YouTube analytics, trend measurements, or predictions. Validate independently."
].join("\n")}